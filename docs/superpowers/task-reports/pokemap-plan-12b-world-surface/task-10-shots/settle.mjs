// usage: node settle.mjs <tag> -- GBA World first-load: world payload -> last tile, render request timings, long tasks
import { open } from "./lib.mjs";
import { guard } from "./guard.mjs";
const [tag] = process.argv.slice(2);
const { browser, page, wait, shot } = await open();
const out = {}; await guard(page, out);
const req = new Map(); const done = []; let world = null;
page.on("request", (r) => { const p = new URL(r.url()).pathname; if (p.startsWith("/api/render/")) req.set(r, Date.now()); });
page.on("requestfinished", (r) => { const p = new URL(r.url()).pathname; if (p === "/api/world") world = Date.now(); if (req.has(r)) done.push({ s: req.get(r), e: Date.now() }); });
await page.goto("http://127.0.0.1:5183/"); await wait(Number(process.env.PRE ?? 3000));
await page.evaluate(() => { window.__lt = []; new PerformanceObserver((l) => { for (const e of l.getEntries()) window.__lt.push(Math.round(e.duration)); }).observe({ type: "longtask", buffered: false }); });
await page.getByRole("group", { name: "View" }).getByRole("button", { name: "World" }).click();
const click = Date.now();
await wait(1000); await shot(`gba-settle-${tag}-1s`);
await wait(9000);
const s = done.map((d) => d.s - world).sort((a, b) => a - b), e = done.map((d) => d.e - world).sort((a, b) => a - b), dur = done.map((d) => d.e - d.s).sort((a, b) => a - b);
const med = (a) => a[Math.floor(a.length / 2)];
Object.assign(out, { tag, worldAfterClick: world - click, renders: done.length, firstReqAfterWorld: s[0], lastReqAfterWorld: s.at(-1), firstDone: e[0], lastDone: e.at(-1), medianReqMs: med(dur), maxReqMs: dur.at(-1), readout: await page.locator(".world-canvas__zoom-readout").textContent({ timeout: 500 }).catch(() => null), longTasks: await page.evaluate(() => window.__lt) });
await shot(`gba-settle-${tag}-10s`);
delete out.applies; console.log(JSON.stringify(out));
await browser.close();
