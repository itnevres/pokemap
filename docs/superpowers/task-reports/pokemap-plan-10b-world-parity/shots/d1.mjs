import { open } from "./lib.mjs";
const { browser, page, wait, shot } = await open();
const out = { net: [] };
page.on("response", (r) => { if (/\/api\/world/.test(r.url()) && r.request().method() !== "GET") out.net.push(r.request().method() + " " + r.url().replace(/^.*\/api/, "") + " " + r.status() + " " + (r.request().postData() || "").slice(0, 150)); });
await page.goto("http://localhost:5183/"); await wait(3000);
await page.getByRole("button", { name: "World", exact: true }).click(); await wait(4000);
const auto = page.getByRole("switch", { name: "Dungeon auto-layout" });
const canvas = page.locator("canvas").first();
const notGreyed = () => page.evaluate(() => [...document.querySelectorAll(".map-tree__map:not(.map-tree__map--greyed)")].map(b => b.textContent));
const before = await notGreyed(); out.notGreyedBefore = before.length; out.railBefore = await page.locator(".world-canvas__rail-count").innerText().catch(() => "none");
await shot("gbc-d-1-auto-on");
await auto.click(); await wait(3500);
out.auto1 = await auto.getAttribute("aria-checked");
const after = await notGreyed(); const newlyGreyed = before.filter(n => !after.includes(n)); out.notGreyedAfter = after.length; out.newlyGreyed = newlyGreyed.length; out.newlyGreyedSample = newlyGreyed.slice(0, 8);
out.railAfter = await page.locator(".world-canvas__rail-count").innerText();
const railNames = await page.locator(".world-canvas__rail-item").allInnerTexts();
out.railHasAllNewlyGreyed = newlyGreyed.every(n => railNames.includes(n));
await shot("gbc-d-2-auto-off");
const name = newlyGreyed[0]; out.name = name;
await page.locator(".world-canvas__rail-filter").fill(name); await wait(500);
const item = page.locator(".world-canvas__rail-item", { hasText: new RegExp("^" + name + "$") }).first();
await item.dragTo(canvas, { targetPosition: { x: 440, y: 380 } }); await wait(2500);
const row = page.locator(".map-tree__map", { hasText: new RegExp("^" + name + "$") }).first();
out.rowGreyedAfterDrag = (await row.getAttribute("class")).includes("greyed");
await page.locator(".world-canvas__rail-filter").fill(""); await wait(300);
out.railAfterDrag = await page.locator(".world-canvas__rail-count").innerText();
await shot("gbc-d-3-dragged-back");
await auto.click(); await wait(3500); out.auto2 = await auto.getAttribute("aria-checked");
out.railFinal = await page.locator(".world-canvas__rail-count").innerText().catch(() => "none");
out.notGreyedFinal = (await notGreyed()).length;
await shot("gbc-d-4-auto-on-again");
console.log(JSON.stringify(out, null, 1)); await browser.close();
